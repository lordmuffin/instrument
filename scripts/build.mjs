#!/usr/bin/env node
// Instrument token build. Reads tokens/instrument.tokens.json (the single source of truth)
// and writes every platform's tokens into dist/. No dependencies: Node 18+ only.
//
//   node scripts/build.mjs            build dist/
//   node scripts/build.mjs --check    build to a temp dir and fail if dist/ differs
//
// Naming follows the "mapping" block in the tokens file:
//   CSS --inst-{name} · SwiftUI Color.inst.{camelName} (asset catalog inst/{name})
//   Android inst_{snake_name} · ECharts themes instrument-light / instrument-dark

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TOKENS_PATH = path.join(ROOT, 'tokens', 'instrument.tokens.json');
const REFERENCE_CSS = path.join(ROOT, 'reference', 'instrument.css');
const ANDROID_PACKAGE = process.env.INSTRUMENT_ANDROID_PACKAGE || 'instrument';

export function loadTokens() {
  return JSON.parse(fs.readFileSync(TOKENS_PATH, 'utf8'));
}

// ---------- helpers ----------
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const snake = (s) => s.replace(/-/g, '_');
const px = (n) => (n === 0 ? '0' : `${n}px`);
const header = (t, c = '//') =>
  `${c} Generated by scripts/build.mjs from tokens/instrument.tokens.json (Instrument v${t.version}).\n${c} Do not edit by hand: change the tokens file and rebuild.\n`;

/** Parse #RGB, #RRGGBB, #RRGGBBAA or rgba(r,g,b,a) into {r,g,b,a} (0-255, a 0-1). */
export function parseColor(v) {
  v = String(v).trim();
  let m = v.match(/^#([0-9a-f]{6})([0-9a-f]{2})?$/i);
  if (m) {
    const n = parseInt(m[1], 16);
    return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255, a: m[2] ? parseInt(m[2], 16) / 255 : 1 };
  }
  m = v.match(/^#([0-9a-f]{3})$/i);
  if (m) {
    const [r, g, b] = m[1].split('').map((c) => parseInt(c + c, 16));
    return { r, g, b, a: 1 };
  }
  m = v.match(/^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)$/i);
  if (m) return { r: +m[1], g: +m[2], b: +m[3], a: m[4] === undefined ? 1 : +m[4] };
  throw new Error(`Unparseable colour: ${v}`);
}
const hex2 = (n) => Math.round(n).toString(16).padStart(2, '0').toUpperCase();
const toHex = ({ r, g, b }) => `#${hex2(r)}${hex2(g)}${hex2(b)}`;
const toArgbHex = (c) => `#${hex2(c.a * 255)}${hex2(c.r)}${hex2(c.g)}${hex2(c.b)}`;
const toKotlin = (c) => `Color(0x${hex2(c.a * 255)}${hex2(c.r)}${hex2(c.g)}${hex2(c.b)})`;

/** Theme colours: { name: { light, dark } } including theme-varying shadows excluded. */
function themeColors(t) {
  const out = {};
  for (const [name, v] of Object.entries(t.color)) out[name] = { light: v.light, dark: v.dark };
  return out;
}
/** Fixed (theme-independent) colours. */
function fixedColors(t) {
  return {
    'channel-live': t.channel.live.value,
    'channel-lab': t.channel.lab.value,
    'channel-other': t.channel.other.value,
    'on-channel': t.channel.on.value,
  };
}
/** Flatten size tokens: nested objects become name-sub (switch-width, live-pill-hud). */
function flatSizes(t) {
  const out = {};
  for (const [k, v] of Object.entries(t.size)) {
    if (typeof v === 'number') out[k] = v;
    else for (const [k2, v2] of Object.entries(v)) out[`${k}-${k2}`] = v2;
  }
  return out;
}
const radii = (t) => Object.fromEntries(Object.entries(t.radius).filter(([, v]) => typeof v === 'number'));
const borders = (t) => Object.fromEntries(Object.entries(t.border).filter(([, v]) => typeof v === 'number'));

// ---------- web ----------
function cssColorBlock(t, theme, indent) {
  const lines = [];
  for (const [name, v] of Object.entries(themeColors(t))) lines.push(`${indent}--inst-${name}: ${v[theme]};`);
  lines.push(`${indent}--inst-shadow-1: ${t.elevation['1'][theme]};`);
  lines.push(`${indent}--inst-shadow-2: ${t.elevation['2'][theme]};`);
  return lines.join('\n');
}

export function buildCssTokens(t) {
  const fam = t.type.family;
  const fixed = [];
  for (const [k, v] of Object.entries(fixedColors(t))) fixed.push(`  --inst-${k}: ${v};`);
  fixed.push(`  --inst-sans: ${fam.sans.web};`);
  fixed.push(`  --inst-mono: ${fam.mono.web};`);
  for (const [k, v] of Object.entries(t.space)) fixed.push(`  --inst-space-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(flatSizes(t))) fixed.push(`  --inst-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(radii(t))) fixed.push(`  --inst-radius-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(borders(t))) fixed.push(`  --inst-border-${k}: ${px(v)};`);
  for (const [k, s] of Object.entries(t.type.scale)) {
    fixed.push(`  --inst-type-${k}-size: ${px(s.size)};`);
    fixed.push(`  --inst-type-${k}-weight: ${s.weight};`);
    fixed.push(`  --inst-type-${k}-line-height: ${s.lineHeight};`);
    fixed.push(`  --inst-type-${k}-tracking: ${s.tracking === 0 ? '0' : `${s.tracking}em`};`);
    fixed.push(`  --inst-type-${k}-family: var(--inst-${s.family});`);
  }
  fixed.push(`  --inst-breathe: ${t.motion.breathe.durationMs}ms;`);
  fixed.push(`  --inst-spin: ${t.motion.spinner.durationMs}ms;`);
  fixed.push(`  --inst-row-saved-hold: ${t.motion.rowSavedHoldMs}ms;`);
  fixed.push(`  --inst-toast: ${t.motion.toastMs}ms;`);
  for (const [k, v] of Object.entries(t.breakpoint)) fixed.push(`  --inst-breakpoint-${k}: ${px(v)}; /* reference only: media queries can't read custom properties */`);

  return `/* ${header(t, '').trim().replace(/\n/g, '\n   ')} */

:root, [data-theme="light"] {
  color-scheme: light;
${cssColorBlock(t, 'light', '  ')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${cssColorBlock(t, 'dark', '    ')}
  }
}

[data-theme="dark"] {
  color-scheme: dark;
${cssColorBlock(t, 'dark', '  ')}
}

/* Theme-independent tokens */
:root {
${fixed.join('\n')}
}
`;
}

/** Component rules: everything in the reference stylesheet after its token blocks. */
function referenceComponents() {
  const css = fs.readFileSync(REFERENCE_CSS, 'utf8');
  const i = css.indexOf('/* Base */');
  if (i < 0) throw new Error('reference/instrument.css: "/* Base */" marker not found');
  return css.slice(i);
}

function buildCssBundle(t, tokensCss) {
  return `${tokensCss}
/* ---------------------------------------------------------------------------
   Components (from reference/instrument.css; tokens above are generated).
   --------------------------------------------------------------------------- */

${referenceComponents()}`;
}

// ---------- SwiftUI ----------
function swiftColorset(light, dark) {
  const comp = (c) => ({
    'color-space': 'srgb',
    components: { alpha: c.a.toFixed(3), red: `0x${hex2(c.r)}`, green: `0x${hex2(c.g)}`, blue: `0x${hex2(c.b)}` },
  });
  const colors = [{ idiom: 'universal', color: comp(parseColor(light)) }];
  if (dark !== undefined)
    colors.push({ idiom: 'universal', appearances: [{ appearance: 'luminosity', value: 'dark' }], color: comp(parseColor(dark)) });
  return JSON.stringify({ colors, info: { author: 'instrument', version: 1 } }, null, 2) + '\n';
}

function buildSwift(t, files) {
  const base = 'swift/Instrument.xcassets';
  files[`${base}/Contents.json`] = JSON.stringify({ info: { author: 'instrument', version: 1 } }, null, 2) + '\n';
  files[`${base}/inst/Contents.json`] =
    JSON.stringify({ info: { author: 'instrument', version: 1 }, properties: { 'provides-namespace': true } }, null, 2) + '\n';
  const props = [];
  for (const [name, v] of Object.entries(themeColors(t))) {
    files[`${base}/inst/${name}.colorset/Contents.json`] = swiftColorset(v.light, v.dark);
    props.push(`    /// ${t.color[name].use}\n    public let ${camel(name)} = Color("inst/${name}", bundle: InstrumentAssets.bundle)`);
  }
  for (const [name, v] of Object.entries(fixedColors(t))) {
    files[`${base}/inst/${name}.colorset/Contents.json`] = swiftColorset(v);
    props.push(`    public let ${camel(name)} = Color("inst/${name}", bundle: InstrumentAssets.bundle)`);
  }
  const weight = (w) => ({ 400: '.regular', 600: '.semibold', 700: '.bold' })[w] || '.regular';
  const styles = Object.entries(t.type.scale).map(([k, s]) => {
    return `    /// ${s.use}
    public static let ${camel(k)} = InstTextStyle(size: ${s.size}, weight: ${weight(s.weight)}, lineHeight: ${s.lineHeight}, tracking: ${s.tracking}, mono: ${s.family === 'mono'}, uppercase: ${s.case === 'upper'})`;
  });
  const nums = (obj, prefix = 's') =>
    Object.entries(obj)
      .map(([k, v]) => `    public static let ${/^\d/.test(k) ? prefix + k : camel(k)}: CGFloat = ${v}`)
      .join('\n');

  files['swift/InstrumentTokens.swift'] = `${header(t)}
import SwiftUI

/// Where the Instrument colour sets live. Defaults to the app bundle; set this once at launch
/// if you vendor Instrument.xcassets into a Swift package instead (e.g. Bundle.module).
public enum InstrumentAssets {
    nonisolated(unsafe) public static var bundle: Bundle = .main
}

/// Instrument colours. Use as Color.inst.surface, Color.inst.accent, ...
/// Light and dark come from the asset catalog appearances; channel colours are fixed.
public struct InstColors: Sendable {
${props.join('\n')}
}

public extension Color {
    static let inst = InstColors()
}

public struct InstTextStyle: Sendable {
    public let size: CGFloat
    public let weight: Font.Weight
    public let lineHeight: CGFloat
    /// Tracking in em; multiply by size for points.
    public let tracking: CGFloat
    public let mono: Bool
    public let uppercase: Bool

    public var font: Font {
        Font.system(size: size, weight: weight, design: mono ? .monospaced : .default).monospacedDigit()
    }
    public var kerning: CGFloat { tracking * size }
    public var lineSpacing: CGFloat { (lineHeight - 1) * size }
}

/// Type scale. Text("…").instStyle(InstType.body)
public enum InstType {
${styles.join('\n')}
}

public extension View {
    func instStyle(_ s: InstTextStyle) -> some View {
        self.font(s.font).kerning(s.kerning).lineSpacing(s.lineSpacing).textCase(s.uppercase ? .uppercase : nil)
    }
}

public enum InstSpace {
${nums(t.space)}
}

public enum InstRadius {
${nums(radii(t), 'r')}
}

public enum InstSize {
${nums(flatSizes(t))}
}

public enum InstMotion {
    public static let breathe: Double = ${t.motion.breathe.durationMs / 1000}
    public static let spinner: Double = ${t.motion.spinner.durationMs / 1000}
    public static let rowSavedHold: Double = ${t.motion.rowSavedHoldMs / 1000}
    public static let toast: Double = ${t.motion.toastMs / 1000}
}
`;
}

// ---------- Android ----------
function buildAndroid(t, files) {
  const xml = (body) => `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${header(t, '').trim().replace(/\n/g, ' ')} -->\n<resources>\n${body}\n</resources>\n`;
  const colorRes = (theme) => {
    const lines = Object.entries(themeColors(t)).map(([n, v]) => {
      const c = parseColor(v[theme]);
      return `    <color name="inst_${snake(n)}">${c.a < 1 ? toArgbHex(c) : toHex(c)}</color>`;
    });
    if (theme === 'light')
      for (const [n, v] of Object.entries(fixedColors(t))) lines.push(`    <color name="inst_${snake(n)}">${toHex(parseColor(v))}</color>`);
    return lines.join('\n');
  };
  files['android/res/values/inst_colors.xml'] = xml(colorRes('light'));
  files['android/res/values-night/inst_colors.xml'] = xml(colorRes('dark'));

  const dimens = [];
  for (const [k, v] of Object.entries(t.space)) dimens.push(`    <dimen name="inst_space_${k}">${v}dp</dimen>`);
  for (const [k, v] of Object.entries(flatSizes(t))) dimens.push(`    <dimen name="inst_${snake(k)}">${v}dp</dimen>`);
  for (const [k, v] of Object.entries(radii(t))) dimens.push(`    <dimen name="inst_radius_${snake(k)}">${v}dp</dimen>`);
  for (const [k, v] of Object.entries(borders(t))) dimens.push(`    <dimen name="inst_border_${snake(k)}">${v}dp</dimen>`);
  for (const [k, s] of Object.entries(t.type.scale)) dimens.push(`    <dimen name="inst_type_${snake(k)}">${s.size}sp</dimen>`);
  files['android/res/values/inst_dimens.xml'] = xml(dimens.join('\n'));

  const fields = Object.keys(themeColors(t)).map((n) => `    val ${camel(n)}: Color,`).join('\n');
  const inst = (theme) =>
    Object.entries(themeColors(t))
      .map(([n, v]) => `    ${camel(n)} = ${toKotlin(parseColor(v[theme]))},`)
      .join('\n');
  const fixed = Object.entries(fixedColors(t))
    .map(([n, v]) => `    val ${camel(n)} = ${toKotlin(parseColor(v))}`)
    .join('\n');
  files['android/compose/InstTheme.kt'] = `${header(t)}
package ${ANDROID_PACKAGE}

import androidx.compose.foundation.isSystemInDarkTheme
import androidx.compose.runtime.Composable
import androidx.compose.runtime.CompositionLocalProvider
import androidx.compose.runtime.Immutable
import androidx.compose.runtime.staticCompositionLocalOf
import androidx.compose.ui.graphics.Color

@Immutable
data class InstColors(
${fields}
)

val lightInstColors = InstColors(
${inst('light')}
)

val darkInstColors = InstColors(
${inst('dark')}
)

/** Theme-independent colours (release-channel badge). */
object InstChannel {
${fixed}
}

val LocalInstColors = staticCompositionLocalOf { darkInstColors }

@Composable
fun InstTheme(darkTheme: Boolean = isSystemInDarkTheme(), content: @Composable () -> Unit) {
    CompositionLocalProvider(LocalInstColors provides if (darkTheme) darkInstColors else lightInstColors, content = content)
}

object Inst {
    val colors: InstColors
        @Composable get() = LocalInstColors.current
}
`;
}

// ---------- ECharts ----------
function buildECharts(t, files) {
  const c = (n, theme) => t.color[n][theme];
  for (const theme of ['light', 'dark']) {
    const axis = {
      axisLine: { show: true, lineStyle: { color: c('control', theme), width: t.chart.baseline.strokeWidth } },
      axisTick: { show: false },
      axisLabel: { color: c('text-2', theme), fontSize: t.type.scale.micro.size, fontFamily: t.type.family.mono.web },
      splitLine: { show: true, lineStyle: { color: c('line', theme), width: t.chart.grid.strokeWidth } },
    };
    const theme_ = {
      color: t.chart['series-order'].map((n) => c(n, theme)),
      backgroundColor: 'transparent',
      textStyle: { color: c('text', theme), fontFamily: t.type.family.sans.web },
      title: { textStyle: { color: c('text', theme) }, subtextStyle: { color: c('text-2', theme) } },
      legend: { textStyle: { color: c('text-2', theme), fontSize: t.type.scale.meta.size }, itemWidth: t.chart.legend.swatch, itemHeight: t.chart.legend.swatch },
      tooltip: {
        backgroundColor: c('inverse', theme),
        borderWidth: 0,
        textStyle: { color: c('on-inverse', theme), fontSize: t.type.scale.meta.size },
        extraCssText: `box-shadow: ${t.elevation['1'][theme]}; border-radius: 0;`,
      },
      categoryAxis: { ...axis, splitLine: { show: false } },
      valueAxis: axis,
      timeAxis: axis,
      line: { symbol: 'circle', symbolSize: 4, lineStyle: { width: 1.5 } },
      bar: { itemStyle: { borderRadius: 0 } },
      // Instrument chart conventions (not read by ECharts; for app code):
      instrument: {
        mean: { color: c('text', theme), width: t.chart.mean.strokeWidth, type: t.chart.mean.dash },
        container: { borderColor: 'series', borderWidth: t.chart.container.strokeWidth, color: 'transparent' },
      },
    };
    files[`echarts/instrument-${theme}.json`] = JSON.stringify(theme_, null, 2) + '\n';
  }
}

// ---------- flat ----------
function buildFlat(t, files) {
  const flat = { version: t.version, light: {}, dark: {}, fixed: {} };
  for (const [n, v] of Object.entries(themeColors(t))) {
    flat.light[n] = v.light;
    flat.dark[n] = v.dark;
  }
  Object.assign(flat.fixed, fixedColors(t));
  for (const [k, v] of Object.entries(t.space)) flat.fixed[`space-${k}`] = v;
  for (const [k, v] of Object.entries(flatSizes(t))) flat.fixed[k] = v;
  for (const [k, v] of Object.entries(radii(t))) flat.fixed[`radius-${k}`] = v;
  files['tokens.flat.json'] = JSON.stringify(flat, null, 2) + '\n';
}

// ---------- main ----------
export function buildAll(t = loadTokens()) {
  const files = {};
  const tokensCss = buildCssTokens(t);
  files['web/instrument.tokens.css'] = tokensCss;
  files['web/instrument.css'] = buildCssBundle(t, tokensCss);
  buildSwift(t, files);
  buildAndroid(t, files);
  buildECharts(t, files);
  buildFlat(t, files);
  files['VERSION'] = `${t.version}\n`;
  return files;
}

function writeTree(dir, files) {
  fs.rmSync(dir, { recursive: true, force: true });
  for (const [rel, content] of Object.entries(files)) {
    const p = path.join(dir, rel);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, content);
  }
}

function listTree(dir, base = dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? listTree(p, base) : [path.relative(base, p)];
  });
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const files = buildAll();
  const dist = path.join(ROOT, 'dist');
  if (process.argv.includes('--check')) {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'instrument-'));
    writeTree(tmp, files);
    const a = new Set(listTree(dist));
    const b = new Set(listTree(tmp));
    const problems = [];
    for (const f of b) {
      if (!a.has(f)) problems.push(`missing in dist/: ${f}`);
      else if (fs.readFileSync(path.join(dist, f), 'utf8') !== fs.readFileSync(path.join(tmp, f), 'utf8')) problems.push(`stale: dist/${f}`);
    }
    for (const f of a) if (!b.has(f)) problems.push(`unexpected in dist/: ${f}`);
    if (problems.length) {
      console.error(problems.join('\n') + '\n\ndist/ is out of date. Run: make build');
      process.exit(1);
    }
    console.log(`dist/ is up to date (${b.size} files).`);
  } else {
    writeTree(dist, files);
    console.log(`Built ${Object.keys(files).length} files into dist/ (Instrument v${loadTokens().version}).`);
  }
}
